/**
 * upload.js — load test for the resume upload endpoint.
 *
 * Prerequisites:
 *   APP_ENV=staging npx tsx prisma/seed-load.ts
 *   (seed-load also writes load/fixtures/minimal.pdf)
 *
 * Run (Git Bash):
 *   docker run --rm -i \
 *     -e BASE_URL=http://host.docker.internal:3001 \
 *     -v "$(pwd -W)/load":/load \
 *     grafana/k6:latest run /load/k6/upload.js
 */
import http from 'k6/http'
import { check } from 'k6'
import { SharedArray } from 'k6/data'
import { fail } from 'k6'

const BASE_URL = __ENV.BASE_URL || 'http://localhost:3001'

const students = new SharedArray('students', function () {
  return JSON.parse(open('../../load/students.local.json'))
})

// Binary PDF fixture — generated by seed-load.ts using pdf-lib
const PDF_BYTES = open('../../load/fixtures/minimal.pdf', 'b')

export function setup() {
  if (students.length === 0) fail('Need students — run: APP_ENV=staging npx tsx prisma/seed-load.ts')
}

export const options = {
  scenarios: {
    resume_upload: {
      executor: 'constant-vus',
      vus: 20,
      duration: '2m',
    },
  },
  thresholds: {
    // Uploads include S3 PutObject; allow up to 5 s p95
    'http_req_duration{name:upload_resume}': ['p(95)<5000'],
    'http_req_failed': ['rate<0.05'],
  },
}

export default function resumeUpload() {
  const student = students[(__VU - 1) % students.length]
  const data = { file: http.file(PDF_BYTES, 'resume.pdf', 'application/pdf') }
  const res = http.post(`${BASE_URL}/api/uploads/RESUME`, data, {
    headers: { Cookie: student.cookie },
    tags: { name: 'upload_resume' },
  })
  check(res, {
    'upload 2xx': (r) => r.status >= 200 && r.status < 300,
    'response has key': (r) => {
      try {
        const body = JSON.parse(r.body)
        return body.ok === true && typeof body.key === 'string'
      } catch (_) {
        return false
      }
    },
  })
}
