test('mobile member navigation and avatar menu support keyboard and sign-out', async ({ page }) => {
  await loginAs(page, { role: 'STUDENT' })
  await page.goto('/en/s/jobs')
  await page.setViewportSize({ width: 375, height: 812 })
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('dialog').getByRole('link', { name: 'Companies', exact: true }).click()
  await expect(page).toHaveURL(/\/en\/s\/companies$/)
  await expect(page.getByRole('dialog')).toBeHidden()
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(0)
  const avatar = page.getByRole('button', { name: 'Account menu', exact: true })
  await avatar.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('menu')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(avatar).toBeFocused()
  await snapshot(page, 'student-companies-mobile')
  await accessible(page)
  await avatar.click()
  await page.getByRole('menuitem', { name: 'Sign out', exact: true }).click()
  await expect(page).toHaveURL(/\/en\/login/)
  await page.goto('/en/s/jobs')
  await expect(page).toHaveURL(/\/en\/login\?redirect=/)
})

