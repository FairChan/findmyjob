async function snapshot(page: Page, name: string) {
  await page.screenshot({ path: path.resolve(process.env.REDESIGN_SHOT_DIR ?? '.reports/member-navigation/screenshots', `${name}.png`), fullPage: true })
}

async function accessible(page: Page) {
  const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa']).analyze()
  expect(result.violations.filter(v => v.impact === 'serious' || v.impact === 'critical').map(v => `${v.id}: ${v.nodes.map(n => n.target.join(' ')).join(', ')}`)).toEqual([])
}

test('student browsing and profile retain member navigation', async ({ page }) => {
  const { userId } = await loginAs(page, { role: 'STUDENT' })
  await e2eDb.studentProfile.create({
    data: { userId, fullName: 'Navigation Student', completeness: 80, onboardingStep: 5 },
  })
  await page.goto('/zh/s/profile')
  await expect(page.getByRole('button', { name: '账户菜单', exact: true })).toBeVisible()
  const nav = page.getByRole('navigation', { name: '学生导航', exact: true })
  await nav.getByRole('link', { name: '找职位', exact: true }).click()
  await expect(page).toHaveURL(/\/zh\/s\/jobs$/)
  await expect(page.getByRole('search')).toBeVisible()
  await expect(page.locator('main')).toHaveCount(1)
  await expect(page.locator('header').getByRole('link', { name: '登录', exact: true })).toHaveCount(0)
  await accessible(page)
  await snapshot(page, 'student-jobs-desktop')
  await page.getByRole('button', { name: '账户菜单', exact: true }).click()
  await page.getByRole('menuitem', { name: '个人资料', exact: true }).click()
  await expect(page).toHaveURL(/\/zh\/s\/profile$/)
  await expect(nav).toBeVisible()
  await page.locator('#pf-fullName').fill('Updated Navigation Student')
  await page.locator('#pf-workAuth').selectOption('STUDENT_PASS')
  await page.locator('section[aria-labelledby="section-basic"]').getByRole('button').click()
  await expect(page.locator('section[aria-labelledby="section-basic"]').getByRole('status')).toBeVisible()
  await page.getByRole('button', { name: '账户菜单', exact: true }).click()
  await expect(page.getByRole('menu')).toContainText('Updated Navigation Student')
  await page.keyboard.press('Escape')
  await page.goto('/zh/jobs?q=navigation&type=INTERNSHIP')
  await expect(page).toHaveURL(/\/zh\/s\/jobs\?q=navigation&type=INTERNSHIP/)
  await expect(page.locator('#jobs-q')).toHaveValue('navigation')
  await expect(page.locator('#jobs-type')).toHaveValue('INTERNSHIP')
  await page.goto('/zh/companies')
  await expect(page).toHaveURL(/\/zh\/s\/companies$/)
  await page.goto('/zh')
  await expect(page.getByRole('button', { name: '账户菜单', exact: true })).toBeVisible()
  await expect(page.locator('header').getByRole('link', { name: '登录', exact: true })).toHaveCount(0)
})

