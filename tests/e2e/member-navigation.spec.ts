test('member company page links current positions into member job detail', async ({ page }) => {
  const { userId } = await loginAs(page, { role: 'STUDENT' })
  await e2eDb.studentProfile.create({ data: { userId, fullName: 'Company Visitor', completeness: 80, onboardingStep: 5 } })
  const company = await e2eDb.company.create({ data: { legalName: `Navigation Company ${Date.now()}`, verificationStatus: 'VERIFIED', isActive: true } })
  const job = await e2eDb.job.create({ data: { companyId: company.id, createdById: userId, title: 'Member navigation job', type: 'INTERNSHIP', workMode: 'REMOTE', description: 'Synthetic member job description', status: 'PUBLISHED', publishedAt: new Date() } })
  await page.goto(`/zh/companies/${company.id}`)
  await expect(page).toHaveURL(new RegExp(`/zh/s/companies/${company.id}$`))
  await page.getByRole('link', { name: /Member navigation job/ }).click()
  await expect(page).toHaveURL(new RegExp(`/zh/s/jobs/${job.id}$`))
  await expect(page.getByText('Synthetic member job description')).toBeVisible()
  // The modal keeps navigation visible behind it while hiding the background from assistive technology.
  await expect(page.getByRole('button', { name: '账户菜单', exact: true, includeHidden: true })).toBeVisible()
  await expect(page.getByRole('link', { name: company.legalName, exact: true })).toHaveAttribute('href', `/zh/s/companies?company=${company.id}`)
})

test('admin can publish curated visitor selections and bilingual copy', async ({ page, browser }) => {
  const previous = await e2eDb.systemSetting.findUnique({ where: { key: PUBLIC_SHOWCASE_KEY } })
  const { userId } = await loginAs(page, { role: 'ADMIN' })
  const company = await e2eDb.company.create({ data: { legalName: `Curated Company ${Date.now()}`, verificationStatus: 'VERIFIED', isActive: true } })
  const job = await e2eDb.job.create({ data: { companyId: company.id, createdById: userId, title: `Curated Internship ${Date.now()}`, type: 'INTERNSHIP', workMode: 'REMOTE', description: 'PRIVATE_SHOWCASE_DESCRIPTION', status: 'PUBLISHED', publishedAt: new Date() } })
  const visitor = await browser.newPage({ baseURL: new URL(page.url()).origin, storageState: { cookies: [], origins: [] } })
  try {
    await e2eDb.systemSetting.upsert({ where: { key: PUBLIC_SHOWCASE_KEY }, create: { key: PUBLIC_SHOWCASE_KEY, value: DEFAULT_PUBLIC_SHOWCASE }, update: { value: DEFAULT_PUBLIC_SHOWCASE } })
    await page.goto('/en/admin/settings')
    const form = page.getByTestId('showcase-settings')
    await form.getByRole('combobox').nth(0).selectOption(job.id)
    await form.getByRole('combobox').nth(1).selectOption(company.id)
    await form.locator('input[id$="jobs-en-title"]').fill('Curated opportunities for graduates')
    await form.locator('input[id$="companies-zh-title"]').fill('认识值得加入的企业')
    await form.getByRole('button', { name: 'Save showcase', exact: true }).click()
    await expect(form.getByRole('status')).toHaveText('Visitor showcase saved.')
    const saved = await e2eDb.systemSetting.findUniqueOrThrow({ where: { key: PUBLIC_SHOWCASE_KEY } })
    expect(saved.value).toMatchObject({ jobIds: [job.id], companyIds: [company.id] })
    expect(await e2eDb.auditLog.count({ where: { actorId: userId, targetId: PUBLIC_SHOWCASE_KEY, action: 'setting.update' } })).toBe(1)
    await visitor.goto('/en/jobs')
    await expect(visitor.getByRole('heading', { level: 1 })).toHaveText('Curated opportunities for graduates')
    await expect(visitor.getByRole('heading', { name: job.title, exact: true })).toBeVisible()
    await expect(visitor.locator('body')).not.toContainText('PRIVATE_SHOWCASE_DESCRIPTION')
    await visitor.goto('/zh/companies')
    await expect(visitor.getByRole('heading', { level: 1 })).toHaveText('认识值得加入的企业')
    await expect(visitor.getByRole('heading', { name: company.legalName, exact: true })).toBeVisible()
  } finally {
    await visitor.close()
    if (previous) await e2eDb.systemSetting.update({ where: { key: PUBLIC_SHOWCASE_KEY }, data: { value: previous.value as Prisma.InputJsonValue } })
    else await e2eDb.systemSetting.deleteMany({ where: { key: PUBLIC_SHOWCASE_KEY } })
    await e2eDb.job.delete({ where: { id: job.id } })
    await e2eDb.company.delete({ where: { id: company.id } })
  }
})
