import { test, expect } from '@playwright/test'
import { e2eDb as db } from './helpers/db'
import { evidence } from './helpers/billing-t02-ui'
import { ResumeReviewFixture, t01Copy } from './helpers/resume-parse-t01-ui'

test.use({ storageState: { cookies: [], origins: [] }, trace: 'off', screenshot: 'off', video: 'off' })
test.describe('T01 private resume review without external AI', () => {
  test.setTimeout(240_000)
  let fixture: ResumeReviewFixture
  test.beforeEach(async ({ page }) => {
    expect(test.info().config.workers).toBe(1)
    fixture = new ResumeReviewFixture(page); await fixture.init()
  })
  test.afterEach(async () => { if (fixture) await fixture.cleanup() })

  for (const locale of ['zh', 'en'] as const) {
    test(locale + ': explicit consent, selected confirmation, real stale edit, discard and disabled withdrawal', async ({ page }, info) => {
      const copy = t01Copy(locale), t = copy.resumeParse
      const first = await fixture.resume()
      const initial = await fixture.state()
      await page.goto('/' + locale + '/s/resume')
      const panel = page.getByTestId('resume-parse-panel')
      await expect(panel.getByLabel(t.consentLabel, { exact: true })).not.toBeChecked()
      await expect(panel.getByRole('button', { name: t.saveConsent, exact: true })).toBeDisabled()
      await expect(panel.getByRole('button', { name: t.request, exact: true })).toBeDisabled()
      await panel.getByLabel(t.consentLabel, { exact: true }).check()
      await panel.getByRole('button', { name: t.saveConsent, exact: true }).click()
      await expect(panel.getByText(t.consentSaved, { exact: true })).toBeVisible()
      expect(await db.resumeParseDraft.count({ where: { resume: { studentId: fixture.profileId } } })).toBe(0)
      expect(await fixture.state()).toEqual(initial)
      await fixture.seedReady(first.id)
      await panel.getByRole('button', { name: t.loadDraft, exact: true }).click()
      await expect(panel.getByText(t.reviewTitle, { exact: true })).toBeVisible()
      for (const field of ['headline', 'summary', 'skills', 'languages', 'educations', 'experiences']) {
        await expect(panel.getByTestId('parse-group-' + field).getByRole('checkbox')).not.toBeChecked()
      }
      expect(await fixture.state()).toEqual(initial)
      await evidence(page, info, locale + '-private-ready', '[data-testid="resume-parse-panel"]')
      const headline = panel.getByTestId('parse-group-headline')
      await headline.getByRole('textbox', { name: t.editValue, exact: true }).fill('SYNTHETIC 学生确认标题')
      await headline.getByRole('checkbox').check()
      await panel.getByRole('button', { name: t.confirm, exact: true }).click()
      await expect(panel.getByText(t.saved, { exact: true })).toBeVisible()
      await page.waitForLoadState('networkidle')
      const saved = await fixture.state()
      expect(saved.headline).toBe('SYNTHETIC 学生确认标题')
      expect(saved.editRevision).toBe(initial.editRevision + 1)
      for (const field of ['summary', 'skills', 'languages', 'educations', 'experiences', 'contact', 'schoolVerifiedAt', 'workAuth', 'visibility', 'onboardingStep'] as const) expect(saved[field]).toEqual(initial[field])
      expect((await db.resumeParseDraft.findUniqueOrThrow({ where: { resumeId: first.id } })).payload).toBeNull()
      expect((await db.resumeFile.findUniqueOrThrow({ where: { id: first.id } })).parsedJson).toBeNull()

      const second = await fixture.resume(); await fixture.seedReady(second.id); await fixture.open(locale, second.id)
      await headline.getByRole('textbox', { name: t.editValue, exact: true }).fill('SYNTHETIC retained review edit')
      await headline.getByRole('checkbox').check()
      const manual = await page.context().newPage()
      try {
        await manual.goto('/' + locale + '/s/profile')
        await manual.waitForLoadState('networkidle')
        await manual.locator('#pf-summary').fill('SYNTHETIC later manual summary')
        await expect(manual.locator('#pf-summary')).toHaveValue('SYNTHETIC later manual summary')
        const section = manual.locator('section[aria-labelledby="section-skills"]')
        await section.getByRole('button', { name: copy.profile.saveSection, exact: true }).click()
        await expect(section.getByRole('status')).toHaveText(copy.profile.saveSuccess)
        await manual.waitForLoadState('networkidle')
      } finally { await manual.close() }
      const afterManual = await fixture.state()
      expect(afterManual.summary).toBe('SYNTHETIC later manual summary')
      expect(afterManual.editRevision).toBe(saved.editRevision + 1)
      await panel.getByRole('button', { name: t.confirm, exact: true }).click()
      await expect(panel.getByRole('alert')).toHaveText(t.error.conflict)
      await expect(headline.getByRole('textbox', { name: t.editValue, exact: true })).toHaveValue('SYNTHETIC retained review edit')
      expect(await fixture.state()).toEqual(afterManual)
      await evidence(page, info, locale + '-stale-review', '[data-testid="resume-parse-panel"]')
      await panel.getByRole('button', { name: t.compareAgain, exact: true }).click()
      await expect(panel.getByText(t.compared, { exact: true })).toBeVisible()
      await expect(headline.getByRole('checkbox')).not.toBeChecked()
      await expect(headline.getByRole('textbox', { name: t.editValue, exact: true })).toHaveValue('SYNTHETIC retained review edit')
      await headline.getByRole('checkbox').check()
      await panel.getByRole('button', { name: t.confirm, exact: true }).click()
      await expect(panel.getByText(t.saved, { exact: true })).toBeVisible()
      await page.waitForLoadState('networkidle')
      const reconciled = await fixture.state()
      expect(reconciled.headline).toBe('SYNTHETIC retained review edit')
      expect(reconciled.summary).toBe('SYNTHETIC later manual summary')
      expect(reconciled.editRevision).toBe(afterManual.editRevision + 1)

      const third = await fixture.resume(); await fixture.seedReady(third.id); await fixture.open(locale, third.id)
      await panel.getByRole('button', { name: t.discard, exact: true }).click()
      const discardDialog = page.getByRole('dialog', { name: t.discard, exact: true })
      await expect(discardDialog.getByText(t.discardConfirm, { exact: true })).toBeVisible()
      await evidence(page, info, locale + '-discard-confirmation', '[role="dialog"]')
      await discardDialog.getByRole('button', { name: t.cancel, exact: true }).click()
      expect((await db.resumeParseDraft.findUniqueOrThrow({ where: { resumeId: third.id } })).state).toBe('READY')
      await expect(panel.getByRole('button', { name: t.discard, exact: true })).toBeFocused()
      await panel.getByRole('button', { name: t.discard, exact: true }).click()
      await page.getByRole('dialog', { name: t.discard, exact: true }).getByRole('button', { name: t.discard, exact: true }).click()
      await expect(panel.getByText(t.discarded, { exact: true })).toBeVisible()
      expect(await db.resumeParseDraft.findUniqueOrThrow({ where: { resumeId: third.id } })).toMatchObject({ state: 'CANCELLED', generation: 2, payload: null })
      expect(await fixture.state()).toEqual(reconciled)

      const fourth = await fixture.resume(); await fixture.seedReady(fourth.id)
      await fixture.gate(false); await fixture.open(locale, fourth.id)
      await expect(panel.getByText(t.unavailable, { exact: true })).toBeVisible()
      await expect(page.getByRole('button', { name: copy.resume.uploadButton, exact: true }).and(page.locator('button'))).toBeEnabled()
      await expect(panel.getByRole('link', { name: t.manualEdit, exact: true })).toHaveAttribute('href', '/' + locale + '/s/profile')
      await expect(panel.getByRole('button', { name: t.confirm, exact: true })).toBeDisabled()
      await panel.getByRole('button', { name: t.withdraw, exact: true }).click()
      await expect(panel.getByText(t.consentWithdrawn, { exact: true })).toBeVisible()
      expect(await db.resumeParseDraft.findUniqueOrThrow({ where: { resumeId: fourth.id } })).toMatchObject({ state: 'CANCELLED', generation: 2, payload: null })
      expect(await fixture.state()).toEqual(reconciled)
      const latest = await db.consent.findFirstOrThrow({ where: { userId: fixture.userId, type: 'AI_RESUME_PARSE' }, orderBy: [{ createdAt: 'desc' }, { id: 'desc' }] })
      expect(latest.granted).toBe(false)
      expect(await db.auditLog.count({ where: { actorId: fixture.userId, action: 'resume.parse.confirm' } })).toBe(2)
      await evidence(page, info, locale + '-disabled-withdrawn', '[data-testid="resume-parse-panel"]')
    })
  }
})
